"""Emit a C table of frozen modules for what CPython needs before imports work.

The interpreter imports `encodings` while initializing (for the filesystem and
standard stream codecs), before the bundle importer `bootstrap.py` installs
exists. CPython does not freeze it (see `Tools/build/freeze_modules.py`), so a
module carries this table, which the shim installs as `PyImport_FrozenModules`
before initialization. The running interpreter must be the version embedded in
the module, since the bytecode format is per version.

Usage: freeze_encodings.py --stdlib LIBDIR --out OUT.c [--expect-version X.Y]
"""

import argparse
import marshal
import sys
from pathlib import Path

# (module name, path under the standard library, is a package)
MODULES = [
    ("encodings", "encodings/__init__.py", True),
    ("encodings.aliases", "encodings/aliases.py", False),
    ("encodings.ascii", "encodings/ascii.py", False),
    ("encodings.latin_1", "encodings/latin_1.py", False),
    ("encodings.utf_8", "encodings/utf_8.py", False),
    ("encodings.utf_8_sig", "encodings/utf_8_sig.py", False),
]


def parse_args() -> argparse.Namespace:
    """Parse the command line."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--stdlib", type=Path, required=True, help="The standard library's root."
    )
    parser.add_argument("--out", type=Path, required=True, help="The C file to write.")
    parser.add_argument(
        "--expect-version",
        help="The `X.Y` the bytecode is for; fails when this interpreter differs.",
    )
    return parser.parse_args()


def freeze(stdlib: Path, name: str, relpath: str) -> bytes:
    """Marshal the code of one module as the frozen table holds it."""
    source = (stdlib / relpath).read_bytes()
    code = compile(source, f"<frozen {name}>", "exec", dont_inherit=True)
    return marshal.dumps(code)


def main() -> None:
    """The main entrypoint."""
    args = parse_args()
    version = f"{sys.version_info.major}.{sys.version_info.minor}"
    if args.expect_version and args.expect_version != version:
        raise SystemExit(
            f"freeze_encodings.py runs under Python {version} but the module embeds "
            f"Python {args.expect_version}; their bytecode differs."
        )

    chunks = []
    table = []
    for index, (name, relpath, is_package) in enumerate(MODULES):
        data = freeze(args.stdlib, name, relpath)
        values = ",".join(str(byte) for byte in data)
        chunks.append(f"static const unsigned char frozen_{index}[] = {{{values}}};\n")
        table.append(
            f'    {{"{name}", frozen_{index}, {len(data)}, {int(is_package)}}},\n'
        )

    with open(args.out, "w", encoding="utf-8") as handle:
        handle.write(f"/* Generated by freeze_encodings.py for Python {version}. */\n")
        handle.write("#include <Python.h>\n\n")
        handle.writelines(chunks)
        handle.write("\nconst struct _frozen rules_venv_py_wasm_frozen_modules[] = {\n")
        handle.writelines(table)
        handle.write("    {0, 0, 0, 0},\n};\n")
    print(f"froze {len(MODULES)} modules for Python {version}")


if __name__ == "__main__":
    main()
